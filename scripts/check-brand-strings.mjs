const WORD = /(?<![A-Za-z0-9_])SlicerX(?![A-Za-z0-9_])/

/** A line without its comment, keeping string contents. `state` carries an open template literal across lines. */
function code(line, rust, state) {
  let out = ''
  let quote = state.quote
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (quote) {
      out += c
      if (c === '\\') out += line[++i] ?? ''
      else if (c === quote) quote = ''
      continue
    }
    if (c === '/' && line[i + 1] === '/') break
    if (c === '"' || c === '`' || (!rust && c === "'")) quote = c
    out += c
  }
  // Only template literals span lines; a stray quote never carries over.
  state.quote = quote === '`' ? quote : ''
  return out
}

/** Hard-coded names in one file's text: [{ line, text }]. */
export function scan(path, text) {
  const rust = path.endsWith('.rs')
  const hits = []
  const state = { quote: '', block: false }
  const lines = text.split('\n')
  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i]
    const t = raw.trim()
    // Rust test modules sit at the end of the file.
    if (rust && t === '#[cfg(test)]') break
    if (state.block) {
      if (t.includes('*/')) state.block = false
      continue
    }
    if (!state.quote && t.startsWith('/*')) {
      if (!t.includes('*/')) state.block = true
      continue
    }
    if (!state.quote && t.startsWith('*')) continue
    const c = code(raw, rust, state)
    if (!WORD.test(c)) continue
    const kept = KEPT.some((k) => k.file.test(path) && (typeof k.text === 'string' ? c.includes(k.text) : k.text.test(c)))
    if (!kept) hits.push({ line: i + 1, text: t })
  }
  return hits
}

/** The files in scope: tracked or new, tests left out. */
export function files(cwd = process.cwd()) {
  return execFileSync('git', ['ls-files', '-co', '--exclude-standard', '--', ...SCOPE], { cwd, encoding: 'utf8' })
    .split('\n')
    .filter((f) => /\.(ts|tsx|rs)$/.test(f) && !/\.test\.tsx?$|_tests?\.rs$|\.d\.ts$|\/tests?\//.test(f))
}

export function check(cwd = process.cwd()) {
  const out = []
  for (const f of files(cwd)) {
    let text
    try {
      text = readFileSync(`${cwd}/${f}`, 'utf8')
    } catch {
      continue
    }
    for (const h of scan(f, text)) out.push(`${f}:${h.line}: ${h.text.slice(0, 160)}`)
  }
  return out
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const hits = check()
  for (const h of hits) console.log(h)
  if (hits.length) {
    console.error(`check-brand-strings: ${hits.length} hard-coded SlicerX in text people read. Use productName() (TypeScript) or app_name() (Rust), or add the line to KEPT with the reason.`)
    process.exit(1)
  }
}
