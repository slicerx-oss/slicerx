// Builds src/icons/tool-icons.ts and src/icons/tool-icons.css from icons/tool: the 32 and 24 px drawings as drawn, the
// 16 px ones as snapped (snapped16.json). Fails on a drawing with no snapped 16 px version or the other way round.
// Run: node packages/ui/scripts/gen-tool-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tool = resolve(here, '../icons/tool')
const { ICONS, SET } = await import(pathToFileURL(resolve(tool, 'draw.mjs')).href)
const { TOOL_ICON_CSS } = await import(pathToFileURL(resolve(tool, 'css.mjs')).href)
const snapped = JSON.parse(readFileSync(resolve(tool, 'snapped16.json'), 'utf8'))

const names = Object.keys(ICONS)
const unsnapped = names.filter((n) => !snapped[n])
const stray = Object.keys(snapped).filter((n) => !ICONS[n])
if (unsnapped.length) throw new Error('drawn but not snapped (run snap-tool-icons.mjs): ' + unsnapped.join(', '))
if (stray.length) throw new Error('snapped but not drawn: ' + stray.join(', '))
const listed = SET.flatMap(([, keys]) => keys)
const unlisted = names.filter((n) => !listed.includes(n))
if (unlisted.length) throw new Error('drawn but in no group: ' + unlisted.join(', '))

const rows = names.map((n) => `  ${JSON.stringify(n)}: { 32: ${JSON.stringify(ICONS[n](32))}, 24: ${JSON.stringify(ICONS[n](24))}, 16: ${JSON.stringify(snapped[n])} },`)
const ts = `// SPDX-License-Identifier: Apache-2.0
// Copyright (C) 2026 The SlicerX contributors
// Generated by scripts/gen-tool-icons.mjs from icons/tool. Do not edit.
/** The shaded tool icons: inner svg markup per size, each size drawn on its own grid; 16 px is snapped to whole pixels. */
export const TOOL_ICONS = {
${rows.join('\n')}
} as const satisfies Record<string, Record<32 | 24 | 16, string>>

export type ToolIconName = keyof typeof TOOL_ICONS
export type ToolIconSize = 32 | 24 | 16

/** The icons in the order the ribbon's tabs group them, for galleries and checks. */
export const TOOL_ICON_GROUPS: Readonly<Record<string, readonly ToolIconName[]>> = ${JSON.stringify(Object.fromEntries(SET), null, 2)}
`
writeFileSync(resolve(here, '../src/icons/tool-icons.ts'), ts)
writeFileSync(resolve(here, '../src/icons/tool-icons.css'), `/* SPDX-License-Identifier: Apache-2.0 */\n/* Copyright (C) 2026 The SlicerX contributors */\n/* Generated by scripts/gen-tool-icons.mjs from icons/tool/css.mjs. Do not edit. */\n${TOOL_ICON_CSS}`)
console.log(`${names.length} tool icons`)
