/**
 * A small but realistic G-code file: a 40 mm square with an outer wall and
 * infill per layer, a retraction and travel between them, and the comments
 * Orca writes. `speed` is the print speed in mm/s.
 */
export function sampleGcode(o: { layer: number; speed: number; nozzle: number; bed: number; retract: number; heightMm?: number; slicer?: string }): string {
  const h = o.heightMm ?? 8
  const ePerMm = (o.layer * 0.42) / (Math.PI * 0.875 ** 2)
  const f = (v: number): string => v.toFixed(4)
  const out = [`; generated by ${o.slicer ?? 'SlicerX'}`, '; filament_diameter = 1.75', `M140 S${o.bed}`, `M104 S${o.nozzle}`, `M190 S${o.bed}`, `M109 S${o.nozzle}`, 'G90', 'M83', 'G28', 'M106 S0']
  let z = 0
  let layer = 0
  while (z + o.layer <= h + 1e-9) {
    z = Math.round((z + o.layer) * 1000) / 1000
    layer++
    out.push(';LAYER_CHANGE', `;Z:${z}`, `G1 Z${z} F600`)
    if (layer === 3) out.push('M106 S255')
    out.push(';TYPE:Outer wall', 'G1 X10 Y10 F12000', `G1 F${o.speed * 60 * 0.6}`)
    for (const [x, y] of [[50, 10], [50, 50], [10, 50], [10, 10]] as const) out.push(`G1 X${x} Y${y} E${f(40 * ePerMm)}`)
    out.push(`G1 E-${o.retract} F2400`, 'G1 X12 Y12 F12000', `G1 E${o.retract} F2400`)
    out.push(';TYPE:Sparse infill', `G1 F${o.speed * 60}`)
    for (let k = 0; k < 8; k++) {
      const y = 12 + k * 4.5
      out.push(`G1 X${k % 2 ? 12 : 48} Y${y} E${f(36 * ePerMm)}`, `G1 Y${y + 4.5} E${f(4.5 * ePerMm)}`)
    }
  }
  out.push('M107', 'M104 S0', 'M140 S0')
  return `${out.join('\n')}\n`
}

