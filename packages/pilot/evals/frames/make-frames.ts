// Draws the stored camera frames for the check-in replay evals: simple
// diagrams of a print on a build plate, not photographs. Replay runs only need
// a real PNG to travel from the camera API to the model request; judging what
// a model reads from real frames needs live runs with photos.
// Run: npx tsx evals/frames/make-frames.ts
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deflateSync } from 'node:zlib'

const W = 320
const H = 240
type Rgb = [number, number, number]

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
function crc32(b: Uint8Array): number {
  let c = 0xffffffff
  for (const x of b) c = (CRC[(c ^ x) & 0xff] ?? 0) ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
function chunk(type: string, data: Uint8Array): Buffer {
  const out = Buffer.alloc(12 + data.length)
  out.writeUInt32BE(data.length, 0)
  out.write(type, 4, 'ascii')
  Buffer.from(data).copy(out, 8)
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length)
  return out
}
function png(px: Uint8Array): Buffer {
  const raw = Buffer.alloc((W * 3 + 1) * H)
  for (let y = 0; y < H; y++) {
    raw[y * (W * 3 + 1)] = 0
    Buffer.from(px.subarray(y * W * 3, (y + 1) * W * 3)).copy(raw, y * (W * 3 + 1) + 1)
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(W, 0)
  ihdr.writeUInt32BE(H, 4)
  ihdr.set([8, 2, 0, 0, 0], 8)
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', new Uint8Array())])
}

function canvas() {
  const px = new Uint8Array(W * H * 3)
  const set = (x: number, y: number, c: Rgb): void => {
    if (x < 0 || y < 0 || x >= W || y >= H) return
    px.set(c, (Math.floor(y) * W + Math.floor(x)) * 3)
  }
  const rect = (x0: number, y0: number, x1: number, y1: number, c: Rgb): void => {
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) set(x, y, c)
  }
  const line = (x0: number, y0: number, x1: number, y1: number, c: Rgb, w = 1): void => {
    const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 1)
    for (let i = 0; i <= n; i++) rect(x0 + ((x1 - x0) * i) / n, y0 + ((y1 - y0) * i) / n, x0 + ((x1 - x0) * i) / n + w, y0 + ((y1 - y0) * i) / n + w, c)
  }
  return { px, set, rect, line }
}

const BG: Rgb = [30, 32, 42]
const PLATE: Rgb = [92, 97, 112]
const PLATE_EDGE: Rgb = [120, 126, 142]
const PART: Rgb = [236, 236, 240]
const PART_TOP: Rgb = [250, 250, 252]
const SHADOW: Rgb = [16, 17, 22]
const NOZZLE: Rgb = [200, 160, 60]

function scene(draw: (c: ReturnType<typeof canvas>) => void): Buffer {
  const c = canvas()
  c.rect(0, 0, W, H, BG)
  c.rect(20, 150, 300, 225, PLATE)
  c.line(20, 150, 300, 150, PLATE_EDGE, 2)
  draw(c)
  return png(c.px)
}

const frames: Record<string, Buffer> = {
  // A part about a third done, sitting flat.
  'midprint-clean.png': scene((c) => {
    c.rect(110, 120, 210, 190, PART)
    c.rect(110, 112, 210, 120, PART_TOP)
    c.rect(150, 70, 170, 104, NOZZLE)
  }),
  // The same part with its bottom left corner lifted off the plate: a dark wedge under it.
  'corner-lifting.png': scene((c) => {
    c.rect(110, 120, 210, 190, PART)
    c.rect(110, 112, 210, 120, PART_TOP)
    for (let x = 110; x < 140; x++) c.rect(x, 190 - Math.round((140 - x) * 0.35), x + 1, 191, SHADOW)
    c.rect(150, 70, 170, 104, NOZZLE)
  }),
  // A loose tangle of filament around the nozzle above a short base.
  'spaghetti.png': scene((c) => {
    c.rect(120, 170, 200, 190, PART)
    let seed = 7
    const rnd = (): number => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff)
    for (let k = 0; k < 40; k++) {
      let x = 130 + rnd() * 60
      let y = 100 + rnd() * 70
      for (let s = 0; s < 12; s++) {
        const nx = x + (rnd() - 0.5) * 18
        const ny = y + (rnd() - 0.5) * 14
        c.line(x, y, nx, ny, PART)
        x = nx
        y = ny
      }
    }
    c.rect(150, 70, 170, 104, NOZZLE)
  }),
}

const here = dirname(fileURLToPath(import.meta.url))
for (const [name, bytes] of Object.entries(frames)) writeFileSync(join(here, name), bytes)
// The same frames as a module, so the scenarios load them in Node and in the browser dev harness.
const entries = Object.entries(frames).map(([name, bytes]) => `  '${name.replace(/\.png$/, '')}': '${bytes.toString('base64')}',`)
writeFileSync(
  join(here, 'index.ts'),
  `// SPDX-License-Identifier: Apache-2.0\n// Copyright (C) 2026 The SlicerX contributors\n// Generated by make-frames.ts. Do not edit by hand.\n/** Stored camera frames (PNG, base64) for the check-in replay evals. */\nexport const FRAMES = {\n${entries.join('\n')}\n} as const\n\nexport type FrameName = keyof typeof FRAMES\n`,
)
process.stdout.write(`${Object.keys(frames).length} frames written to ${here}\n`)
