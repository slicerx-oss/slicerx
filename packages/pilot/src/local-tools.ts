// What a local model is sent of each tool, and what that may cost. A local model's context is small (context.ts), and
// its build turn is the fullest request it gets, so tool text reaches it only when it is listed here on purpose: a tool's
// description when the row says description (a tool with its own localDescription sends that instead), and a field's
// description only at the paths in fields (local-schema.ts writes them). Anything not listed, such as a field added
// later for cloud models, reaches cloud turns only. A tool with no row sends a local model no description at all.
//
// tokens is the most the tool's local form may cost, counted as toolsTokens counts it (context.ts) with the name as a
// local request writes it (encodeToolName), and LOCAL_BUILD_CAP the most the tools of a new part's local turn may cost
// together. The app's mimir-local-context test and pilot's local-tools test hold every tool a local model is sent to
// its row, so a change that makes one cost more raises its row here, in the same diff, where it is read.

export interface LocalTool {
  /** The most this tool's local form may cost, in toolsTokens. */
  readonly tokens: number
  /** Its full description reaches a local model; without it, only its localDescription does, or none. */
  readonly description?: true
  /** The field paths (local-schema.ts) whose description reaches a local model. */
  readonly fields?: readonly string[]
}

