// A single pass G-code reader: layers, temperatures, feed rates, retraction,
// fan, volumetric flow and time by feature. It walks the text line by line
// with indexOf, keeps only counters and small histograms, and never builds a
// list of moves, so large files stay fast. File text is untrusted: only
// numbers and short labels come out of it.

export interface GcodeStats {
  lines: number
  moves: number
  layers: number
  maxZMm: number
  /** Distinct set temperatures in order of appearance, C. `nozzlePrinting` holds only the nozzle temperatures that
   * extruding moves ran at, so start G-code steps such as a probing or wipe temperature are left out of it. */
  temps: { nozzle: number[]; bed: number[]; chamber: number[]; nozzlePrinting: number[] }
  feed: { maxPrintMmS: number; typicalPrintMmS: number; maxTravelMmS: number }
  retractions: { count: number; totalMm: number; typicalMm: number; firmware: number }
  fan: { maxPct: number; changes: number }
  extrusion: { relative: boolean; filamentMm: number; filamentDiameterMm: number }
  flow: { peakMm3s: number; p95Mm3s: number }
  /** The filament profile's max volumetric speed, mm3/s, from an Orca or Bambu Studio config comment; the largest
   * when the file has several filaments. The slicer held every move to it. */
  profileMaxFlowMm3s: number | null
  /** Estimated from move lengths and feed rates, no acceleration; rough. */
  movesTimeS: number
  /** The slicer's own estimate from a header comment, when present. */
  slicerTimeS: number | null
  timeByFeature: { feature: string; s: number; pct: number }[]
  /** Short label from a "generated by" comment, cut to 60 characters. */
  generator: string | null
}

/** "1d 2h 3m 4s", "2h 05m", "12m 3s" to seconds. Null when nothing parses. */
export function parseDuration(s: string): number | null {
  let total = 0
  let hit = false
  for (const m of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi)) {
    const v = Number(m[1])
    const u = (m[2] ?? '').toLowerCase()
    total += u === 'd' ? v * 86400 : u === 'h' ? v * 3600 : u === 'm' ? v * 60 : v
    hit = true
  }
  return hit ? Math.round(total) : null
}

/** Weighted quantile from a histogram of value / bin (rounded) -> weight. */
function quantile(hist: Map<number, number>, q: number, bin: number): number {
  const entries = [...hist.entries()].sort((a, b) => a[0] - b[0])
  const total = entries.reduce((s, [, w]) => s + w, 0)
  if (total <= 0) return 0
  let acc = 0
  for (const [k, w] of entries) {
    acc += w
    if (acc >= q * total - 1e-9) return Math.round(k * bin * 10) / 10
  }
  return Math.round((entries[entries.length - 1]?.[0] ?? 0) * bin * 10) / 10
}

