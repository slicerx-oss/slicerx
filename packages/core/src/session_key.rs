/// Request options a session never reads: they shape the output only.
const FREE_OPTIONS: &[&str] = &[
    "shards",
    "emitGcode",
    "emitPreview",
    "nowUnix",
    "nowOffsetMinutes",
    "thumbnail",
    "plateName",
    "plateNumber",
    "modelName",
    "layerGcode",
];

/// The key of the session `req` prepares: its plate with each mesh named by its content hash (`mesh_hash`, None
/// when a mesh is unknown), its settings without [`SESSION_FREE_KEYS`] and its options without the output-only
/// ones. Two requests with the same key slice to the same bytes on one session. Paint is in the mesh hash as its
/// paint texts ([`crate::Mesh::content_hash`]).
pub fn session_key(req: &SliceRequest, mesh_hash: &dyn Fn(&str) -> Option<u64>) -> Option<u64> {
    let mut plate = serde_json::to_value(&req.plate).ok()?;
    named_by_hash(&mut plate, mesh_hash)?;
    let mut config = req.config.clone();
    if let Some(map) = config.as_object_mut() {
        for k in SESSION_FREE_KEYS {
            map.remove(*k);
        }
    }
    let mut options = serde_json::to_value(&req.options).ok()?;
    if let Some(map) = options.as_object_mut() {
        for k in FREE_OPTIONS {
            map.remove(*k);
        }
    }
    let text = serde_json::to_vec(&serde_json::json!([plate, config, options])).ok()?;
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in text {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    Some(h)
}

/// Every `mesh` reference in the plate (objects, their volumes) replaced by that mesh's content hash.
fn named_by_hash(v: &mut Value, mesh_hash: &dyn Fn(&str) -> Option<u64>) -> Option<()> {
    match v {
        Value::Object(map) => {
            for (k, child) in map.iter_mut() {
                if k == "mesh" {
                    let id = match child {
                        Value::String(s) => s.clone(),
                        Value::Number(n) => n.to_string(),
                        _ => continue,
                    };
                    *child = Value::String(format!("{:016x}", mesh_hash(&id)?));
                } else {
                    named_by_hash(child, mesh_hash)?;
                }
            }
        }
        Value::Array(items) => {
            for child in items {
                named_by_hash(child, mesh_hash)?;
            }
        }
        _ => {}
    }
    Some(())
}
