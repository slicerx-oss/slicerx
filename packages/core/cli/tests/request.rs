//! `sx slice --request` and `sx schema`: the CLI's JSON surface.

use std::io::Write;
use std::process::{Command, Stdio};

fn sx() -> Command {
    Command::new(env!("CARGO_BIN_EXE_sx"))
}

fn fixture(name: &str) -> String {
    format!("{}/tests/fixtures/{name}", env!("CARGO_MANIFEST_DIR"))
}

#[test]
fn request_file_round_trip() {
    let dir = std::env::temp_dir().join(format!("sx-cli-test-{}", std::process::id()));
    let out = sx()
        .args(["slice", "--request", &fixture("cube-request.json"), "--out-dir"])
        .arg(&dir)
        .output()
        .unwrap();
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    assert_eq!(v["schemaVersion"], 1);
    assert_eq!(v["engine"], "sx");
    assert_eq!(v["layerCount"], 50);
    assert_eq!(v["layerZ"].as_array().unwrap().len(), 50);
    let gcode = std::fs::read(dir.join("slice.gcode")).unwrap();
    assert_eq!(v["gcodeBytes"], gcode.len());
    assert!(String::from_utf8_lossy(&gcode).contains("SET_PRINT_STATS_INFO TOTAL_LAYER=50"));
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn request_from_stdin_and_bad_input() {
    let body = std::fs::read_to_string(fixture("cube-request.json"))
        .unwrap()
        .replace("\"cube.stl\"", &format!("{:?}", fixture("cube.stl")));
    let mut child = sx()
        .args(["slice", "--request", "-"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(body.as_bytes()).unwrap();
    let out = child.wait_with_output().unwrap();
    assert!(out.status.success());
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    assert_eq!(v["gcodeSha256"].as_str().unwrap().len(), 64);

    let mut child = sx()
        .args(["slice", "--request", "-"])
        .stdin(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(b"{\"plate\":").unwrap();
    assert_eq!(child.wait_with_output().unwrap().status.code(), Some(3));
}

