        assert!(
            w[2] - w[0] > 19.0 && w[3] - w[1] > 19.0,
            "{how}: no outer wall on the first layer {w:?}"
        );
        assert!(
            runs.iter().any(|b| near(b, w[0], w[1])),
            "{how}: no ear at the first point {runs:?} {w:?}"
        );
