// Writes src/toolbox/index.ts: every file in src/toolbox with a default export is one tool. Run after adding a tool;
// test/registry.test.ts fails when the index is out of date. `--check` prints the difference and exits 1 instead.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'toolbox')

export function toolIndex() {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .filter((f) => /^export default /m.test(readFileSync(join(dir, f), 'utf8')))
    .sort()
  const name = (f) => f.replace(/\.ts$/, '').replace(/-([a-z])/g, (_m, c) => c.toUpperCase())
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    '// Copyright (C) 2026 The SlicerX contributors',
    '// Generated by scripts/tool-index.mjs from the files in this folder. Do not edit by hand.',
    "import type { ServerToolFactory } from './deps'",
    ...files.map((f) => `import ${name(f)} from './${f.replace(/\.ts$/, '')}'`),
    '',
    '/** Every server tool, one file each. */',
    `export const SERVER_TOOLS: ServerToolFactory[] = [${files.map(name).join(', ')}]`,
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = toolIndex()
  const path = join(dir, 'index.ts')
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== want) {
      console.error('src/toolbox/index.ts is out of date: run node scripts/tool-index.mjs')
      process.exit(1)
    }
  } else writeFileSync(path, want)
}
