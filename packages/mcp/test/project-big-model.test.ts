// Another slicer's project whose main model is over the 64 MiB that `text` reads, with its geometry inline and no
// model_settings.config: slicerx_inspect_project names the app that wrote it and counts the plate's build items, and a
// design open finds its main model. The model is plain XML that compresses well, so the archive stays small.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { beforeAll, describe, expect, it } from 'vitest'
import { readDesigns } from '../src/design'
import { MAX_TEXT_BYTES, readZip, writeZip } from '../src/zip'
import { connect, data } from './helpers'

const vertex = '     <vertex x="-4.48749924" y="-6.09670019" z="11.8898945"/>\n'
const head = '<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">\n <metadata name="slic3rpe:Version3mf">1</metadata>\n <metadata name="Application">PrusaSlicer-2.9.6</metadata>\n <resources>\n  <object id="1" type="model">\n   <mesh>\n    <vertices>\n'
const tail = '    </vertices>\n    <triangles>\n     <triangle v1="0" v2="1" v3="2"/>\n    </triangles>\n   </mesh>\n  </object>\n </resources>\n <build>\n  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 100 100 5" printable="1"/>\n  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 150 100 5" printable="1"/>\n  <item objectid="1" transform="1 0 0 0 1 0 0 0 1 200 100 5" printable="0"/>\n </build>\n</model>\n'
// Past the cap by a few MiB, so the build element sits beyond it too.
const model = Buffer.from(head + vertex.repeat(Math.ceil((MAX_TEXT_BYTES + 4 * 1024 * 1024) / vertex.length)) + tail)
let archive: Buffer

beforeAll(() => {
  archive = writeZip([
    { name: '3D/3dmodel.model', data: model },
    { name: 'Metadata/Slic3r_PE.config', data: '; generated by PrusaSlicer 2.9.6\n\n; layer_height = 0.2\n; perimeters = 3\n; filament_type = PLA\n' },
  ])
})

describe('a project whose main model is over 64 MiB', () => {
  it('is inspected: the app that wrote it and its one plate of printable items', async () => {
    expect(model.length).toBeGreaterThan(MAX_TEXT_BYTES)
    expect(archive.length).toBeLessThan(8 * 1024 * 1024)
    const h = await connect()
    const path = join(h.dir, 'big.3mf')
    writeFileSync(path, archive)
    const r = await h.call('slicerx_inspect_project', { file: path })
    expect(r.isError, JSON.stringify(r.content)).toBeFalsy()
    const out = data<{ has_settings: boolean; plates: unknown[]; import_report: { source?: string } }>(r)
    expect(out.has_settings).toBe(true)
    expect(out.import_report.source).toBe('PrusaSlicer-2.9.6')
    expect(out.plates).toEqual([{ index: 1, objects: 2 }])
  })

  it('gives the start of the model, inflating only that much', () => {
    const zip = readZip(archive)
    expect(zip.head('3D/3dmodel.model', 4096)).toEqual(model.subarray(0, 4096))
    expect(() => zip.text('3D/3dmodel.model')).toThrow(`3D/3dmodel.model is over the ${MAX_TEXT_BYTES} byte limit`)
  })

  it('opens as designs: the main model is found without reading it as text', async () => {
    const asked: string[] = []
    const designs = await readDesigns(async (method) => {
      asked.push(method)
      return { objects: [] }
    }, archive, 'big.3mf')
    expect(designs).toEqual([])
    expect(asked).toEqual(['format.read3mf'])
  })
})
