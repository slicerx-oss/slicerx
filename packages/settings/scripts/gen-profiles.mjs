// Writes profiles/printers.json: one printer profile per model in @slicerx/printer-catalog (build volume,
// nozzles, kinematics, enclosure from the catalog), the G-code flavor and source pages from
// scripts/printer-specs.json, and the limits knowledge/printers holds for the models it covers. Where
// packages/profiles/machine.json (or cura/ultimaker.json) has a model, its G-code flavor and extruder type win.
// Run with `node scripts/gen-profiles.mjs` (Node 24 reads the catalog's TypeScript directly).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const catalog = await import(here('../../connect/catalog/src/index.ts'))
const specs = JSON.parse(readFileSync(here('printer-specs.json'), 'utf8')).models
const knowledge = JSON.parse(readFileSync(here('../knowledge.json'), 'utf8')).printers
const read = (p) => (existsSync(here(p)) ? JSON.parse(readFileSync(here(p), 'utf8')).models : {})
const machine = { ...read('../../profiles/cura/ultimaker.json'), ...read('../../profiles/machine.json') }
const ids = JSON.parse(readFileSync(here('../printer-models.json'), 'utf8')).models

const printers = catalog.PRINTER_MODELS.map((m) => {
  const spec = specs[m.id]
  if (!spec) throw new Error(`no spec for ${m.id}`)
  const k = knowledge[ids[m.id]]
  const limits = {}
  if (k?.motion?.maxSpeed) limits.maxSpeed = k.motion.maxSpeed
  if (k?.motion?.maxAccel) limits.maxAccel = k.motion.maxAccel
  if (k?.hotend?.maxTemp) limits.hotendMaxTemp = k.hotend.maxTemp
  if (k?.bed?.maxTemp) limits.bedMaxTemp = k.bed.maxTemp
  const brand = catalog.brandById(m.brand)
  return {
    id: m.id,
    brand: m.brand,
    vendor: brand?.name ?? m.brand,
    model: m.name,
    kinematics: m.kinematics,
    enclosed: m.enclosed,
    buildVolume: m.buildVolume,
    nozzles: m.nozzles,
    defaultNozzle: m.defaultNozzle,
    nozzleCount: m.nozzleCount,
    flavor: machine[m.id]?.machine?.gcode_flavor ?? spec.flavor,
    ...(machine[m.id]?.machine?.extruder_type ? { directDrive: String(machine[m.id].machine.extruder_type).includes('Direct') } : k?.extruder ? { directDrive: k.extruder.includes('direct') } : {}),
    limits,
    sources: spec.sources,
  }
})
writeFileSync(here('../profiles/printers.json'), JSON.stringify({ comment: 'Generated by scripts/gen-profiles.mjs from the printer catalog, scripts/printer-specs.json and knowledge.json.', printers }, null, 1) + '\n')
console.log(`${printers.length} printer profiles`)
